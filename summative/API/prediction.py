"""
API for my order cycle time model.

POST /predict  -> predicts how many days a health commodity order will take to arrive
POST /retrain  -> retrains the model with an uploaded CSV of new orders
GET  /docs     -> Swagger UI (generated by FastAPI)
"""

import os

import joblib
import pandas as pd
from fastapi import FastAPI, File, HTTPException, UploadFile
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sklearn.base import clone

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(BASE_DIR, "best_model.pkl")
DATA_PATH = os.path.join(BASE_DIR, "training_data.csv")

CATEGORICAL = ["country", "order_type", "transport_mode", "product_category", "health_element",
               "vendor_incoterm", "destination_incoterm"]
NUMERIC = ["ordered_quantity", "unit_price", "est_lead_time_days", "order_year", "order_month"]
FEATURES = CATEGORICAL + NUMERIC
TARGET = "order_cycle_days"

app = FastAPI(
    title="Health commodity order cycle time API",
    description="Predicts how many days a health commodity order takes from order entry to delivery.",
    version="1.0.0",
)

# CORS is a browser rule: a web page can only call this API if its address is allowed here.
# My Flutter app runs on a phone, not in a browser, so CORS does not affect it.
# - allow_origins: my Render address (for Swagger UI) and localhost:8080 for testing Flutter
#   in Chrome. I don't use "*" because then any website could call my API.
# - allow_methods: only GET and POST, because my routes only use those two.
# - allow_headers: only Content-Type and Accept, which is all a JSON request or a file upload needs.
# - allow_credentials: False, because there is no login or cookies.
app.add_middleware(
    CORSMiddleware,
    allow_origins=[
        "https://order-cycle-api.onrender.com",
        "http://localhost:8080",
        "http://127.0.0.1:8080",
    ],
    allow_methods=["GET", "POST"],
    allow_headers=["Content-Type", "Accept"],
    allow_credentials=False,
)


def get_allowed_values(data):
    """The values the model has seen for each categorical column."""
    return {col: sorted(data[col].unique().tolist()) for col in CATEGORICAL}


# the model and the training data are loaded once, when the server starts
model = joblib.load(MODEL_PATH)
training_data = pd.read_csv(DATA_PATH)
allowed_values = get_allowed_values(training_data)


class OrderInput(BaseModel):
    # strict=True means a number sent as text ("100") is rejected instead of converted
    model_config = ConfigDict(
        strict=True,
        json_schema_extra={
            "example": {
                "country": "Rwanda",
                "order_type": "Purchase Order",
                "transport_mode": "Air",
                "product_category": "HIV/AIDS Pharmaceuticals",
                "health_element": "HIV/AIDS",
                "vendor_incoterm": "FCA",
                "destination_incoterm": "DAP",
                "ordered_quantity": 5000,
                "unit_price": 7.5,
                "est_lead_time_days": 150,
                "order_year": 2023,
                "order_month": 3,
            }
        },
    )

    country: str = Field(description="Destination country, for example Rwanda")
    order_type: str = Field(description="Purchase Order or Distribution Order")
    transport_mode: str = Field(description="Air, Land, Sea or Multiple")
    product_category: str = Field(description="For example Laboratory Reagents or Malaria Pharmaceuticals")
    health_element: str = Field(description="For example HIV/AIDS or Malaria")
    vendor_incoterm: str = Field(description="CIP, CPT, DAP, DDP, EXW, FCA, Other or Unknown")
    destination_incoterm: str = Field(description="CIF, CIP, CPT, DAP, DDP, FCA, Other or Unknown")
    ordered_quantity: int = Field(ge=1, le=5_000_000, description="Number of units ordered")
    unit_price: float = Field(gt=0, le=200_000, description="Price of one unit in USD")
    est_lead_time_days: int = Field(ge=0, le=730, description="Lead time estimated when the order is placed, in days")
    order_year: int = Field(ge=2016, le=2030, description="Year the order is entered")
    order_month: int = Field(ge=1, le=12, description="Month the order is entered, 1 to 12")

    @field_validator(*CATEGORICAL)
    @classmethod
    def check_known_value(cls, value, info):
        # the text inputs have to be values the model saw in the training data
        allowed = allowed_values[info.field_name]
        if value not in allowed:
            if len(allowed) <= 8:
                raise ValueError(f"'{value}' is not a known {info.field_name}. Use one of: {', '.join(allowed)}")
            raise ValueError(f"'{value}' is not a known {info.field_name}. The API home page (/) lists them")
        return value


class Prediction(BaseModel):
    predicted_order_cycle_days: float


def predict_cycle_time(row: dict) -> float:
    """Same function as in the notebook, but it uses the model that is already loaded."""
    frame = pd.DataFrame([row])
    return float(model.predict(frame[FEATURES])[0])


@app.get("/")
def home():
    return {
        "message": "Order cycle time API. Open /docs to try it.",
        "allowed_values": allowed_values,
    }


@app.post("/predict", response_model=Prediction)
def predict(order: OrderInput):
    days = predict_cycle_time(order.model_dump())
    return {"predicted_order_cycle_days": round(days, 1)}


@app.post("/retrain")
def retrain(file: UploadFile = File(description="CSV with the same columns as training_data.csv")):
    global model, training_data, allowed_values

    if not file.filename or not file.filename.lower().endswith(".csv"):
        raise HTTPException(status_code=400, detail="Please upload a .csv file")

    try:
        new_rows = pd.read_csv(file.file)
    except Exception:
        raise HTTPException(status_code=400, detail="Could not read the file as a CSV")

    missing = [col for col in FEATURES + [TARGET] if col not in new_rows.columns]
    if missing:
        raise HTTPException(status_code=400, detail=f"Missing columns: {', '.join(missing)}")

    # clean the new rows like in the notebook: numbers must be numbers, no empty cells,
    # and quantity and cycle time have to be more than 0
    new_rows = new_rows[FEATURES + [TARGET]].copy()
    for col in NUMERIC + [TARGET]:
        new_rows[col] = pd.to_numeric(new_rows[col], errors="coerce")
    new_rows = new_rows.dropna()
    new_rows = new_rows[(new_rows[TARGET] > 0) & (new_rows["ordered_quantity"] > 0)]
    new_rows[CATEGORICAL] = new_rows[CATEGORICAL].astype(str)
    if new_rows.empty:
        raise HTTPException(status_code=400, detail="The file has no usable rows")

    combined = pd.concat([training_data, new_rows], ignore_index=True)

    # A random forest cannot keep training on new rows like SGD can with partial_fit.
    # So I make an unfitted copy of the pipeline (same settings) and fit it on old + new data.
    new_model = clone(model)
    new_model.fit(combined[FEATURES], combined[TARGET])

    # save the new model and data, and use them right away in /predict
    joblib.dump(new_model, MODEL_PATH, compress=3)
    combined.to_csv(DATA_PATH, index=False)
    model = new_model
    training_data = combined
    allowed_values = get_allowed_values(combined)

    return {
        "message": "Model retrained. /predict is now using the new model.",
        "rows_added": len(new_rows),
        "total_training_rows": len(combined),
    }
